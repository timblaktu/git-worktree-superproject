//! Multi-repository workspace management
//!
//! This module provides the core functionality for managing workspaces containing
//! multiple git repositories. A workspace is a collection of repositories checked out
//! at specific branches or commits, enabling consistent development environments across
//! multiple related projects.

use crate::config::RepoConfig;
use anyhow::Result;
use std::path::{Path, PathBuf};

// mockall is test-only
#[cfg(test)]
use mockall::automock;

// ============================================================================
// Trait Abstractions
// ============================================================================

/// Git repository operations abstraction for testing
///
/// This trait abstracts git operations to enable mocking in unit tests.
/// Production code uses `RealRepositoryOps` with actual git operations,
/// while tests use `MockRepositoryOps` generated by mockall.
#[cfg_attr(test, automock)]
pub trait RepositoryOps: Send + Sync {
    /// Clone a repository to the specified path and checkout the given branch
    fn clone_repo(&self, url: &str, path: &Path, branch: &str) -> Result<()>;

    /// Pull updates from the remote repository
    /// Returns Ok(true) if changes were pulled, Ok(false) if already up-to-date
    fn pull(&self, path: &Path) -> Result<bool>;

    /// Get the current status of the repository
    fn get_status(&self, path: &Path) -> Result<RepoStatus>;

    /// Get the current branch name
    fn get_current_branch(&self, path: &Path) -> Result<String>;

    /// Checkout a specific reference (branch, tag, or commit)
    fn checkout_ref(&self, path: &Path, reference: &str) -> Result<()>;

    /// Check if a path contains a valid git repository
    fn is_repo(&self, path: &Path) -> bool;
}

/// Workspace management operations
///
/// This trait defines the core workspace management API. It provides methods
/// for creating, switching, syncing, and removing workspaces.
#[cfg_attr(test, automock)]
pub trait WorkspaceManager {
    /// Switch to a workspace (create if it doesn't exist)
    ///
    /// Creates a new workspace with the given name, cloning all repositories
    /// specified in the config. If the workspace already exists, this is a no-op.
    fn switch(&self, workspace_name: &str, config: &WorkspaceConfig) -> Result<SwitchReport>;

    /// Synchronize a workspace by pulling updates from all repositories
    ///
    /// Pulls updates from remote repositories for all non-pinned repos in the workspace.
    fn sync(&self, workspace_name: &str) -> Result<SyncReport>;

    /// List all available workspaces
    fn list(&self) -> Result<Vec<WorkspaceInfo>>;

    /// Remove a workspace
    fn remove(&self, workspace_name: &str) -> Result<()>;

    /// Execute a command in each repository of the workspace
    fn foreach(&self, workspace_name: &str, command: &[String]) -> Result<ForeachResult>;

    /// Get status of workspace(s)
    ///
    /// If workspace_name is None, returns status of all workspaces.
    /// If specified, returns status of the named workspace only.
    fn status(&self, workspace_name: Option<String>) -> Result<StatusReport>;
}

