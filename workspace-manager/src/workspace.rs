//! Multi-repository workspace management
//!
//! This module provides the core functionality for managing workspaces containing
//! multiple git repositories. A workspace is a collection of repositories checked out
//! at specific branches or commits, enabling consistent development environments across
//! multiple related projects.

use crate::config::RepoConfig;
use anyhow::Result;
use std::path::{Path, PathBuf};

// mockall is test-only
#[cfg(test)]
use mockall::automock;

// ============================================================================
// Trait Abstractions
// ============================================================================

/// Git repository operations abstraction for testing
///
/// This trait abstracts git operations to enable mocking in unit tests.
/// Production code uses `RealRepositoryOps` with actual git operations,
/// while tests use `MockRepositoryOps` generated by mockall.
#[cfg_attr(test, automock)]
pub trait RepositoryOps: Send + Sync {
    /// Clone a repository to the specified path and checkout the given branch
    fn clone_repo(&self, url: &str, path: &Path, branch: &str) -> Result<()>;

    /// Pull updates from the remote repository
    fn pull(&self, path: &Path) -> Result<()>;

    /// Get the current status of the repository
    fn get_status(&self, path: &Path) -> Result<RepoStatus>;

    /// Get the current branch name
    fn get_current_branch(&self, path: &Path) -> Result<String>;

    /// Checkout a specific reference (branch, tag, or commit)
    fn checkout_ref(&self, path: &Path, reference: &str) -> Result<()>;

    /// Check if a path contains a valid git repository
    fn is_repo(&self, path: &Path) -> bool;
}

/// Workspace management operations
///
/// This trait defines the core workspace management API. It provides methods
/// for creating, switching, syncing, and removing workspaces.
#[cfg_attr(test, automock)]
pub trait WorkspaceManager {
    /// Switch to a workspace (create if it doesn't exist)
    ///
    /// Creates a new workspace with the given name, cloning all repositories
    /// specified in the config. If the workspace already exists, this is a no-op.
    fn switch(&self, workspace_name: &str, config: &WorkspaceConfig) -> Result<SwitchReport>;

    /// Synchronize a workspace by pulling updates from all repositories
    ///
    /// Pulls updates from remote repositories for all non-pinned repos in the workspace.
    fn sync(&self, workspace_name: &str) -> Result<SyncReport>;

    /// List all available workspaces
    fn list(&self) -> Result<Vec<WorkspaceInfo>>;

    /// Remove a workspace
    fn remove(&self, workspace_name: &str) -> Result<()>;

    /// Execute a command in each repository of the workspace
    fn foreach(&self, workspace_name: &str, command: &[String]) -> Result<ForeachResult>;

    /// Get status of workspace(s)
    ///
    /// If workspace_name is None, returns status of all workspaces.
    /// If specified, returns status of the named workspace only.
    fn status(&self, workspace_name: Option<String>) -> Result<StatusReport>;
}

// ============================================================================
// Domain Types
// ============================================================================

/// Configuration for a workspace
#[derive(Debug, Clone)]
pub struct WorkspaceConfig {
    /// List of repositories to include in the workspace
    pub repos: Vec<RepoConfig>,
    /// Base directory for worktrees
    pub worktree_base: PathBuf,
    /// Default branch name
    pub default_branch: String,
}

/// Information about a workspace
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WorkspaceInfo {
    /// Name of the workspace
    pub name: String,
    /// Path to the workspace directory
    pub path: PathBuf,
    /// Number of repositories in the workspace
    pub repo_count: usize,
}

/// Report from a workspace switch operation
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SwitchReport {
    /// Name of the workspace
    pub workspace_name: String,
    /// Repositories that were newly created
    pub repos_created: Vec<String>,
    /// Repositories that already existed and were skipped
    pub repos_skipped: Vec<String>,
    /// Errors encountered during switch (repo name, error message)
    pub errors: Vec<(String, String)>,
}

/// Report from a workspace sync operation
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SyncReport {
    /// Name of the workspace
    pub workspace_name: String,
    /// Repositories that were updated
    pub repos_updated: Vec<String>,
    /// Repositories that were skipped because they're pinned
    pub repos_pinned: Vec<String>,
    /// Repositories that failed to update (repo name, error message)
    pub repos_failed: Vec<(String, String)>,
}

/// Result from a foreach operation
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ForeachResult {
    /// Outputs from each repository command execution
    pub outputs: Vec<RepoCommandOutput>,
    /// Failures (repo name, error message)
    pub failures: Vec<(String, String)>,
}

/// Output from executing a command in a repository
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RepoCommandOutput {
    /// Name of the repository
    pub repo_name: String,
    /// Standard output from the command
    pub stdout: String,
    /// Standard error from the command
    pub stderr: String,
    /// Exit code from the command
    pub exit_code: i32,
}

/// Status of a repository
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RepoStatus {
    /// Repository is clean with no modifications
    Clean {
        /// Current branch name
        branch: String,
    },
    /// Repository has modified files
    Modified {
        /// Current branch name
        branch: String,
        /// Number of changes
        changes: usize,
    },
    /// Repository has untracked files
    Untracked {
        /// Current branch name
        branch: String,
        /// Number of untracked files
        files: usize,
    },
    /// Repository is not initialized (no commits)
    Uninitialized,
    /// Repository is broken or corrupted
    Broken {
        /// Reason for the broken state
        reason: String,
    },
    /// Repository is in detached HEAD state
    DetachedHead {
        /// Current commit hash
        commit: String,
    },
}

/// Status report for one or more workspaces
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StatusReport {
    /// Status of each workspace
    pub workspaces: Vec<WorkspaceStatus>,
}

/// Status of a single workspace
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WorkspaceStatus {
    /// Name of the workspace
    pub name: String,
    /// Status of each repository in the workspace
    pub repos: Vec<RepositoryStatus>,
}

/// Status of a repository within a workspace
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RepositoryStatus {
    /// Name of the repository
    pub name: String,
    /// Status information
    pub status: RepoStatus,
}

