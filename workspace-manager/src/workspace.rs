/// Configuration for a workspace
#[derive(Debug, Clone)]
pub struct WorkspaceConfig {
    /// List of repositories to include in the workspace
    pub repos: Vec<RepoConfig>,
    /// Base directory for worktrees
    pub worktree_base: PathBuf,
    /// Default branch name
    pub default_branch: String,
}

/// Information about a workspace
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WorkspaceInfo {
    /// Name of the workspace
    pub name: String,
    /// Path to the workspace directory
    pub path: PathBuf,
    /// Number of repositories in the workspace
    pub repo_count: usize,
}

/// Report from a workspace switch operation
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SwitchReport {
    /// Name of the workspace
    pub workspace_name: String,
    /// Repositories that were newly created
    pub repos_created: Vec<String>,
    /// Repositories that already existed and were skipped
    pub repos_skipped: Vec<String>,
    /// Errors encountered during switch (repo name, error message)
    pub errors: Vec<(String, String)>,
}

/// Report from a workspace sync operation
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SyncReport {
    /// Name of the workspace
    pub workspace_name: String,
    /// Repositories that were updated
    pub repos_updated: Vec<String>,
    /// Repositories that were skipped because they're pinned
    pub repos_pinned: Vec<String>,
    /// Repositories that failed to update (repo name, error message)
    pub repos_failed: Vec<(String, String)>,
}

/// Result from a foreach operation
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ForeachResult {
    /// Outputs from each repository command execution
    pub outputs: Vec<RepoCommandOutput>,
    /// Failures (repo name, error message)
    pub failures: Vec<(String, String)>,
}

/// Output from executing a command in a repository
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RepoCommandOutput {
    /// Name of the repository
    pub repo_name: String,
    /// Standard output from the command
    pub stdout: String,
    /// Standard error from the command
    pub stderr: String,
    /// Exit code from the command
    pub exit_code: i32,
}

/// Status of a repository
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RepoStatus {
    /// Repository is clean with no modifications
    Clean {
        /// Current branch name
        branch: String,
    },
    /// Repository has modified files
    Modified {
        /// Current branch name
        branch: String,
        /// Number of changes
        changes: usize,
    },
    /// Repository has untracked files
    Untracked {
        /// Current branch name
        branch: String,
        /// Number of untracked files
        files: usize,
    },
    /// Repository is not initialized (no commits)
    Uninitialized,
    /// Repository is broken or corrupted
    Broken {
        /// Reason for the broken state
        reason: String,
    },
    /// Repository is in detached HEAD state
    DetachedHead {
        /// Current commit hash
        commit: String,
    },
}

/// Status report for one or more workspaces
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StatusReport {
    /// Status of each workspace
    pub workspaces: Vec<WorkspaceStatus>,
}

/// Status of a single workspace
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WorkspaceStatus {
    /// Name of the workspace
    pub name: String,
    /// Status of each repository in the workspace
    pub repos: Vec<RepositoryStatus>,
}

/// Status of a repository within a workspace
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RepositoryStatus {
    /// Name of the repository
    pub name: String,
    /// Status information
    pub status: RepoStatus,
}

