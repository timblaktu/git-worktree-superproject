/// Builder for creating WorkspaceConfig instances
///
/// Provides a fluent API for constructing workspace configurations in tests.
#[derive(Debug, Default)]
pub struct WorkspaceConfigBuilder {
    repos: Vec<RepoConfig>,
    worktree_base: Option<PathBuf>,
    default_branch: String,
}

impl WorkspaceConfigBuilder {
    /// Create a new builder with default values
    pub fn new() -> Self {
        Self {
            repos: Vec::new(),
            worktree_base: None,
            default_branch: "main".to_string(),
        }
    }

    /// Add a repository with a specific branch
    pub fn add_repo(mut self, url: impl Into<String>, branch: impl Into<String>) -> Self {
        self.repos.push(RepoConfig {
            url: url.into(),
            branch: branch.into(),
            git_ref: None,
        });
        self
    }

    /// Add a pinned repository (specific tag or commit)
    pub fn add_pinned_repo(mut self, url: impl Into<String>, reference: impl Into<String>) -> Self {
        self.repos.push(RepoConfig {
            url: url.into(),
            branch: "main".to_string(), // Default branch for pinned repos
            git_ref: Some(reference.into()),
        });
        self
    }

    /// Set the worktree base directory
    pub fn worktree_base(mut self, path: PathBuf) -> Self {
        self.worktree_base = Some(path);
        self
    }

    /// Set the default branch name
    pub fn default_branch(mut self, branch: impl Into<String>) -> Self {
        self.default_branch = branch.into();
        self
    }

    /// Build the final WorkspaceConfig
    pub fn build(self) -> WorkspaceConfig {
        WorkspaceConfig {
            repos: self.repos,
            worktree_base: self
                .worktree_base
                .unwrap_or_else(|| PathBuf::from("worktrees")),
            default_branch: self.default_branch,
        }
    }
}

